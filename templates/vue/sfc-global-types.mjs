import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { isFunction, isObjectLike, isString } from "./server/type-guards.mjs";

/**
 * The very unimport the auto-import plugin scans with, so both read the
 * directories the same way. Imported by URL, not by path: on Windows,
 * `import()` reads `C:\...` as a URL whose scheme is `c:` and refuses it.
 */
const unimportUrl = pathToFileURL(
  createRequire(
    createRequire(import.meta.url).resolve("unplugin-auto-import/package.json"),
  ).resolve("unimport"),
);
/** @type {unknown} */
const unimport = await import(unimportUrl.href);

/**
 * An export of unimport, which this package does not depend on and so has no
 * types for.
 *
 * @param {string} name
 * @returns {unknown}
 */
function unimportExport(name) {
  return isObjectLike(unimport) ? unimport[name] : undefined;
}

/**
 * The function unimport exports as `name`.
 *
 * @param {string} name
 * @returns {Function}
 */
function unimportFunction(name) {
  const exported = unimportExport(name);
  if (!isFunction(exported))
    throw new Error(`unimport exports no function ${name}`);
  return exported;
}

/**
 * A name unimport scanned or resolved: where it comes from, what it is called
 * and whether it is only a type.
 *
 * @typedef {object} ImportedName
 * @property {string} name
 * @property {string} from
 * @property {string} [as]
 */

/**
 * @param {unknown} entry
 * @returns {entry is ImportedName}
 */
function isImportedName(entry) {
  return (
    isObjectLike(entry) &&
    isString(entry.name) &&
    isString(entry.from) &&
    (entry.as === undefined || isString(entry.as))
  );
}

/**
 * The names of type declarations among `entries`, as unimport lists them.
 *
 * @param {unknown} entries
 * @returns {ImportedName[]}
 */
function typeNames(entries) {
  if (!Array.isArray(entries)) throw new Error("unimport listed no names");
  /** @type {unknown[]} */
  const listed = entries;
  /** @type {ImportedName[]} */
  const names = [];
  for (const entry of listed) {
    if (!isObjectLike(entry)) throw new Error("unimport listed a non-name");
    if (!entry.type) continue;
    if (!isImportedName(entry))
      throw new Error("unimport listed a type without a name and a source");
    names.push(entry);
  }
  return names;
}

const HEADER =
  "// Generated by @antelopejs/dms-frontend from the auto-imported types, for\n" +
  "// Vue's SFC compiler (script.globalTypeFiles). Not read by TypeScript.\n";

/** @param {string} path */
const withoutExtension = (path) => path.replace(/\.[cm]?[jt]sx?$/, "");

/**
 * The ambient aliases of the auto-imported types: one per name, in the order
 * the auto-import plugin reads them (Vue's preset, then the scanned
 * directories), the last one winning, as unimport's own deduplication keeps
 * the last of two imports of the same name. A module that exports its own
 * `Component` thus shadows Vue's, for the compiler as for TypeScript.
 *
 * Vue's SFC compiler turns `defineProps<Props>()` into runtime prop types and
 * reads a type from the component's own imports only. A type a module auto-
 * imports (its declared `app/types`, `app/composables`..., and Vue's own `Ref`,
 * `Component`...) is visible to TypeScript through auto-imports.d.ts but not to
 * the compiler, which drops it from the prop without a word: `boolean |
 * RowActionConfig` became `{ type: Boolean }` in a production build. The
 * compiler does read ambient declarations from `script.globalTypeFiles`, but
 * not the `export type { ... } from` re-exports auto-imports.d.ts is made of.
 * These types are therefore written as ambient aliases it can follow, from the
 * same directories and through the same scanner as the auto-imports, before
 * Vite compiles anything, and rewritten when a dev server sees a module's
 * declared directories change.
 *
 * @param {(string | { glob: string, types?: boolean })[]} dirs the auto-import
 *   directories, as handed to the auto-import plugin
 * @param {string} cwd the workspace
 * @returns {Promise<string>}
 */
export async function sfcGlobalTypes(dirs, cwd) {
  const presets = unimportExport("builtinPresets");
  /** @type {unknown} */
  const vue = await unimportFunction("resolvePreset")(
    isObjectLike(presets) ? presets.vue : undefined,
  );
  /** @type {unknown} */
  const scanned = await unimportFunction("scanDirExports")(dirs, {
    cwd,
    types: true,
  });
  /** @type {Map<string, string>} */
  const aliases = new Map();
  for (const entry of [...typeNames(vue), ...typeNames(scanned)]) {
    const name = entry.as ?? entry.name;
    const source = JSON.stringify(withoutExtension(entry.from));
    aliases.set(
      name,
      `declare type ${name} = import(${source}).${entry.name};`,
    );
  }
  return `${HEADER}${[...aliases.values()].join("\n")}\n`;
}

/**
 * Written through a temporary file: a build starting meanwhile reads the
 * previous declarations or the new ones, never a half-written file the
 * compiler would then keep in its cache.
 *
 * @param {string} file
 * @param {string} content
 * @returns {boolean}
 */
function writeIfChanged(file, content) {
  /** @type {string | undefined} */
  let current;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = undefined;
  }
  if (current === content) return false;
  const temporary = `${file}.${process.pid}.tmp`;
  writeFileSync(temporary, content);
  renameSync(temporary, file);
  return true;
}

/**
 * Writes the declarations once, before Vite's config is returned.
 *
 * @param {(string | { glob: string, types?: boolean })[]} dirs
 * @param {string} cwd
 * @param {string} file
 * @returns {Promise<void>}
 */
export async function writeSfcGlobalTypes(dirs, cwd, file) {
  writeIfChanged(file, await sfcGlobalTypes(dirs, cwd));
}

/**
 * Keeps the declarations in step on a dev server: a type file added, renamed
 * or removed rewrites them, and the Vue plugin reloads the components whose
 * props read the file.
 *
 * The file is under the workspace, which Vite watches: rewriting it is the
 * change the Vue plugin reloads the dependent components on. A failed scan or
 * write keeps the previous declarations, since it must not end the dev server.
 *
 * @param {(string | { glob: string, types?: boolean })[]} dirs
 * @param {string} cwd
 * @param {string} file
 * @returns {import("vite").Plugin}
 */
export function sfcGlobalTypesWatcher(dirs, cwd, file) {
  return {
    name: "dms-sfc-global-types",
    apply: "serve",
    configureServer(server) {
      /** @type {ReturnType<typeof setTimeout> | undefined} */
      let pending;
      /** @param {string} path */
      const refresh = (path) => {
        if (!/\.[cm]?[jt]sx?$/.test(path) || path === file) return;
        clearTimeout(pending);
        pending = setTimeout(() => {
          sfcGlobalTypes(dirs, cwd)
            .then((content) => writeIfChanged(file, content))
            .catch(
              /** @param {unknown} error */ (error) =>
                server.config.logger.warn(
                  `Could not update ${file}, the types Vue's SFC compiler ` +
                    `reads: ${error instanceof Error ? error.message : String(error)}`,
                ),
            );
        }, 100);
      };
      for (const event of ["add", "change", "unlink"])
        server.watcher.on(event, refresh);
    },
  };
}
